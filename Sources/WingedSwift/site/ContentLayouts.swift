import Foundation

/// How a ``ContentPage`` — a Markdown file from `Content/` — becomes the body of a page. The site
/// layout still wraps the result.
///
/// ## Example
/// ```swift
/// struct PostLayout: ContentLayout {
///     func body(page: ContentPage, content: HTMLTag) -> HTMLTag {
///         Article {
///             H1(content: page.title)
///             P(content: "\(page.readingMinutes) min read")
///             content
///         }
///     }
/// }
/// ```
public protocol ContentLayout {
    /// The page body.
    ///
    /// - Parameters:
    ///   - page: The Markdown file and its front matter.
    ///   - content: The rendered Markdown.
    @HTMLBuilder func body(page: ContentPage, content: HTMLTag) -> HTMLTag
}

/// The default ``ContentLayout``: an `<article>` with the title, the date and tags when present,
/// and the content.
public struct DefaultContentLayout: ContentLayout {
    /// Creates the layout.
    public init() {}

    public func body(page: ContentPage, content: HTMLTag) -> HTMLTag {
        Article {
            Header {
                H1(content: page.title)
                if page.date != nil || !page.tags.isEmpty {
                    InlineFlow(P {
                        if let date = page.date {
                            Time(datetime: ContentDates.day(date), content: ContentDates.day(date))
                        }
                        for tag in page.tags {
                            " "
                            A(href: TagPages.path(for: tag), content: "#\(tag)").addClass("tag")
                        }
                    }
                    .addClass("meta"))
                }
            }
            content
        }
    }
}

/// How the tag pages look: one page per tag at `/tags/<tag>/`, and an index at `/tags/`.
public protocol TagLayout {
    /// The page listing the content tagged `tag`.
    @HTMLBuilder func body(tag: String, pages: [ContentPage]) -> HTMLTag
    /// The page listing every tag.
    @HTMLBuilder func indexBody(tags: [(tag: String, pages: [ContentPage])]) -> HTMLTag
}

/// The default ``TagLayout``: headings and lists of links.
public struct DefaultTagLayout: TagLayout {
    /// Creates the layout.
    public init() {}

    public func body(tag: String, pages: [ContentPage]) -> HTMLTag {
        H1(content: "#\(tag)")
        Ul {
            for page in pages {
                Li { A(href: page.path, content: page.title) }
            }
        }
    }

    public func indexBody(tags: [(tag: String, pages: [ContentPage])]) -> HTMLTag {
        H1(content: "Tags")
        Ul {
            for entry in tags {
                InlineFlow(Li {
                    A(href: TagPages.path(for: entry.tag), content: "#\(entry.tag)")
                    " (\(entry.pages.count))"
                })
            }
        }
    }
}

enum ContentDates {
    /// `2026-10-15`, in UTC.
    static func day(_ date: Date) -> String {
        String(FeedGenerator.rfc3339(date).prefix(10))
    }
}

enum TagPages {
    static let indexPath = "/tags/"

    static func path(for tag: String) -> String {
        "/tags/\(tagSlug(tag))/"
    }

    /// Groups pages by tag, in slug order, pages in their published order. Tags that share a slug
    /// (`Swift`, `swift`) are one tag, spelled as it first appears.
    static func group(_ pages: [ContentPage]) -> [(tag: String, pages: [ContentPage])] {
        var names: [String: String] = [:]
        var groups: [String: [ContentPage]] = [:]
        for page in pages {
            for tag in page.tags {
                let slug = tagSlug(tag)
                names[slug] = names[slug] ?? tag
                if groups[slug]?.last != page {
                    groups[slug, default: []].append(page)
                }
            }
        }
        return groups.keys.sorted().map { (names[$0] ?? $0, groups[$0] ?? []) }
    }
}

/// The slug rule for tags: lowercase, letters and digits, other runs become `-`.
func tagSlug(_ text: String) -> String {
    var slug = ""
    for character in text.lowercased() {
        if character.isLetter || character.isNumber {
            slug.append(character)
        } else if !slug.hasSuffix("-") {
            slug.append("-")
        }
    }
    let trimmed = slug.trimmingCharacters(in: CharacterSet(charactersIn: "-"))
    return trimmed.isEmpty ? "tag" : trimmed
}

/// A page generated by the site — from a Markdown file or a tag — rather than declared by the user.
struct GeneratedPage: Page {
    var title: String
    var description: String
    var path: String
    var image: String
    var isInSitemap = true
    var date: Date?
    var tags: [String] = []
    let makeBody: () -> HTMLTag

    var body: HTMLTag { makeBody() }
}
